export interface RegionNavigation {place:Place;bounds:BBox;sourceRecordId:string;boundaryReferenceDate:string;purpose:'camera-framing';}
/** Exact province+borough name only. Renamed/new regions and stale map versions return null. */
export function regionNavigation(region:Pick<PropertyRegion,'name'>,map:Pick<MapCatalog2D,'reference_dates'>):RegionNavigation|null {
  if(map.reference_dates.sgis!==REGION_NAVIGATION_SOURCE.referenceDate)return null;
  const row=byName.get(normalizedName(region.name));if(!row)return null;
  const [code,name,west,south,east,north,lon,lat]=row;
  const width=(east-west)*111320*Math.cos(lat*Math.PI/180),height=(north-south)*111320;
  // The existing engines accept an equivalent overhead range. Padding is display-only.
  const range=Math.max(4000,Math.min(600000,Math.max(width,height)*1.25));
  const sourceRecordId=`sgis:20250630:${code.length===2?'sido':'sigungu'}:${code}`;
  return {place:{id:`region-sgis-${code}`,name,region:`지역 보기 · 경계 ${REGION_NAVIGATION_SOURCE.referenceDate}`,lon,lat,range},
    bounds:[west,south,east,north],sourceRecordId,boundaryReferenceDate:REGION_NAVIGATION_SOURCE.referenceDate,purpose:'camera-framing'};
}
export function regionNavigationPlace(region:Pick<PropertyRegion,'name'>,map:Pick<MapCatalog2D,'reference_dates'>):Place|null {
  return regionNavigation(region,map)?.place??null;
}
